// Integration checks run against an isolated in-memory localStorage, never browser data.
import {build} from 'esbuild';
import {writeFile,mkdir,rm} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
await mkdir('.nfc-test',{recursive:true});
const memory=new Map();
globalThis.localStorage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
globalThis.window={localStorage:globalThis.localStorage};
const suite=`
import assert from 'node:assert/strict';
import {useApp} from '../src/store';
import {activeSubscription,day,today} from '../src/data';
const app=()=>useApp.getState();
const accepted=()=>app().data.checkIns.filter(c=>c.decision==='accepted').length;
let checks=0;
const test=(condition,label)=>{assert.ok(condition,label);checks++};
const input={firstName:'Yassine',lastName:'NFC Integration',phone:'0600000000',email:'nfc@example.test',planId:'month-gym',start:day(today()),end:day(new Date(Date.now()+30*86400000)),paymentStatus:'confirmed'};
const enrolled=app().enrollMember(input);test(enrolled.ok,'enrollment');
const id=enrolled.memberId;
test(app().data.members.some(m=>m.id===id),'member in shared directory');
test(!!activeSubscription(app().data,id),'subscription/payment linked');
const card=app().createBlankCard();
test(app().scanCard(card.code).message.includes('non attribuée'),'unassigned denied');
test(app().scanCard(id).message==='Carte inconnue','Studio cannot bypass credential with member ID');
test(app().reassignCard(card.id,id).ok,'blank assignment');
test(app().reassignCard(card.id,'m-002').ok,'blank reassignment');
test(!app().writeCard(card.id,id,'forest').ok,'reserved card cannot be stolen');
app().reassignCard(card.id,id);
test(app().writeCard(card.id,id,'olive').ok,'write');
test(!app().writeCard(card.id,'m-002','forest').ok,'written credential cannot be overwritten');
test(!app().reassignCard(card.id,'m-002').ok,'written credential cannot be reassigned');
test(!app().assignCard('m-002',card.code.toLowerCase()).ok,'case-insensitive duplicate rejected');
let count=accepted();
test(app().scanCard(card.code).ok,'active member accepted');
test(accepted()===count+1,'accepted scan increments attendance');
test(!app().scanCard(card.code).ok,'rapid duplicate denied');
test(accepted()===count+1,'duplicate does not increment attendance');
test(app().inspectCard(card.code,'verify').ok,'verification ignores attendance duplicate');
test(accepted()===count+1,'verification does not count attendance');
let sub=activeSubscription(app().data,id);
app().setSubscriptionStatus(sub.id,'expired');
test(app().scanCard(card.code).message==='Abonnement expiré','same card denied after expiry');
test(accepted()===count+1,'expiry does not increment attendance');
app().subscribe(id,'month-gym','Carte',true);
test(app().scanCard(card.code).ok,'same card accepted after renewal, without reset');
test(accepted()===count+2,'renewed visit recorded');
sub=activeSubscription(app().data,id);app().setSubscriptionStatus(sub.id,'suspended');
test(app().scanCard(card.code).message==='Abonnement suspendu','suspension denied');
app().setSubscriptionStatus(sub.id,'active');
app().revokeCard(card.id,'lost');
test(app().scanCard(card.code).message==='Carte déclarée perdue','lost denied');
const replacement=app().createBlankCard();app().writeCard(replacement.id,id,'nocturne');
test(app().inspectCard(replacement.code,'verify').ok,'replacement valid');
app().revokeCard(replacement.id,'revoked');
test(app().scanCard(replacement.code).message==='Carte révoquée','revocation denied');
test(!app().writeCard(replacement.id,'m-002','forest').ok,'revoked credential cannot be reissued');
test(app().scanCard('UNKNOWN').message==='Carte inconnue','unknown denied');
const pending=app().enrollMember({...input,email:'pending@example.test',paymentStatus:'pending'});
const pendingCard=app().createBlankCard();app().writeCard(pendingCard.id,pending.memberId,'forest');
test(app().scanCard(pendingCard.code).message.includes('Paiement'),'pending payment denied');
const payment=app().data.payments.find(p=>p.memberId===pending.memberId);app().confirmPayment(payment.id);
test(app().scanCard(pendingCard.code).ok,'payment confirmation activates access');
test(app().data.credentials.find(c=>c.id===card.id).lastScanAt,'last scan persisted');
test(app().data.nfcEvents.some(e=>e.credentialId===card.id&&e.action==='Vérification'),'verification history');
const saved=localStorage.getItem('jardin-fitness-os-v2');
test(!!saved,'storage key preserved');
const parsed=JSON.parse(saved).state;
test(parsed.data.credentials.find(c=>c.id===card.id).memberId===id,'assignment serialized');
await useApp.persist.rehydrate();
test(app().data.members.some(m=>m.id===id)&&app().data.nfcEvents.length===parsed.data.nfcEvents.length,'rehydration keeps records and history');
test(app().data.products.length===7&&app().data.sessions.length===42,'unrelated club entities preserved');
const stock=app().data.products.find(p=>p.id==='water').stock;
test(app().sell([{productId:'water',qty:1}],id).ok&&app().data.products.find(p=>p.id==='water').stock===stock-1,'existing POS works');
console.log(checks+' NFC integration checks passed.');
`;
try{
 await writeFile('.nfc-test/suite.ts',suite);
 await build({entryPoints:['.nfc-test/suite.ts'],outfile:'.nfc-test/suite.mjs',bundle:true,platform:'node',format:'esm',packages:'external'});
 await import(pathToFileURL(resolve('.nfc-test/suite.mjs')).href);
}finally{await rm('.nfc-test',{recursive:true,force:true})}
